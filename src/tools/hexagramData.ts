/** 八宫世应表：宫位 → [世爻位, 应爻位]（世应相隔三位） */
export function palaceShiYing(palace: Palace, position: number): { shi: number; ying: number } {
  // 京房八宫：本宫卦世在六爻，一世至五世依次上移，游魂世在四爻，归魂世在三爻
  const shi = position;
  const ying = shi > 3 ? shi - 3 : shi + 3;
  return { shi, ying };
}

