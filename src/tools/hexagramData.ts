/*
 * 易经六十四卦数据表。
 *
 * 排列顺序为「通行本（周易王弼本）卦序」，即 King Wen 卦序，
 * 与 binary 值（7 位二进制，自下而上六爻，1 = 阳爻）无关，
 * 因此本表按序号排列，索引 = 卦序 - 1。
 *
 * 「卦宫」按「京房八宫卦」归类，用于展示所属宫位与世应关系。
 */

export type Yao = 0 | 1; // 1 = 阳（—），0 = 阴（- -）

/** 八卦三爻（自下而上），二进制值 0..7 = 坤 艮 坎 巽 震 离 兑 乾 */
export const TRIGRAM_YAO: Yao[][] = [
  [0, 0, 0], // 坤 地
  [1, 0, 0], // 艮 山
  [0, 1, 0], // 坎 水
  [1, 1, 0], // 巽 风
  [0, 0, 1], // 震 雷
  [1, 0, 1], // 离 火
  [0, 1, 1], // 兑 泽
  [1, 1, 1], // 乾 天
];

export const TRIGRAM_NAMES = ["坤", "艮", "坎", "巽", "震", "离", "兑", "乾"] as const;
export const TRIGRAM_NATURE = ["地", "山", "水", "风", "雷", "火", "泽", "天"] as const;
export const TRIGRAM_SYMBOL = ["☷", "☶", "☵", "☴", "☳", "☲", "☱", "☰"] as const;

/** 京房八宫 */
export type Palace =
  | "乾宫"
  | "坎宫"
  | "艮宫"
  | "震宫"
  | "巽宫"
  | "离宫"
  | "坤宫"
  | "兑宫";

export interface Hexagram {
  /** 卦序（1..64） */
  no: number;
  /** 卦名，如「乾」 */
  name: string;
  /** 上卦（外卦）八卦序号 0..7 */
  upper: number;
  /** 下卦（内卦）八卦序号 0..7 */
  lower: number;
  /** 卦辞（原文） */
  judgment: string;
  /** 象传 / 说明 */
  image: string;
  /** 白话大意（现代解读） */
  meaning: string;
  /** 运势关键词 */
  keywords: string[];
  /** 所主方位 / 季节的简短提示 */
  season: string;
  /** 京房八宫归类 */
  palace: Palace;
}

/** 由上下卦生成「卦象全称」：上卦自然象 + 下卦自然象 */
export function hexagramFullName(upper: number, lower: number): string {
  return `${TRIGRAM_NATURE[upper]}${TRIGRAM_NATURE[lower]}`;
}

/** 由上下卦生成 7 位二进制（bit0 = 初爻） */
export function hexagramBits(upper: number, lower: number): number {
  let bits = 0;
  for (let i = 0; i < 3; i++) {
    if (TRIGRAM_YAO[lower][i]) bits |= 1 << i;
    if (TRIGRAM_YAO[upper][i]) bits |= 1 << (i + 3);
  }
  return bits;
}

/** 八卦组合 → 卦象全称（如「乾为天」「水雷屯」） */
export function hexagramTitle(name: string, upper: number, lower: number): string {
  if (upper === lower) {
    return `${TRIGRAM_NAMES[lower]}为${TRIGRAM_NATURE[lower]}` +
      (name === TRIGRAM_NAMES[lower] ? "" : `（${name}）`);
  }
  return `${TRIGRAM_NATURE[upper]}${TRIGRAM_NATURE[lower]}${name}`;
}

