/** 卦序 → 卦（越界回绕） */
export function hexagramByNo(no: number): Hexagram {
  const i = ((no - 1) % 64 + 64) % 64;
  return HEXAGRAMS[i];
}

/** 二进制值（bit0=初爻）→ 卦 */
export function hexagramByBits(bits: number): Hexagram {
  const b = ((bits % 128) + 128) % 128;
  const lower = b & 7;
  const upper = (b >> 3) & 7;
  return HEXAGRAMS.find((h) => h.upper === upper && h.lower === lower) ?? HEXAGRAMS[0];
}

/** 卦象全称展示（自动处理「八纯卦=本卦名」） */
export function hexagramDisplayName(h: Hexagram): string {
  if (h.upper === h.lower) return `${h.name}为${TRIGRAM_NATURE[h.lower]}`;
  return `${TRIGRAM_NATURE[h.upper]}${TRIGRAM_NATURE[h.lower]}${h.name}`;
}

